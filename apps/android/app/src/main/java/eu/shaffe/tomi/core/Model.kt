enum class DispatchResult {
    /** The relay accepted the item. */
    Sent,

    /** No network or relay error: the caller should retry later (WorkManager back-off). */
    RetryLater,

    /** The item no longer exists locally (cancelled/deleted): nothing to do. */
    NotFound,
}

/** State of the space this device belongs to, as known by the core. */
enum class SpaceState {
    /** Normal operation. */
    Active,

    /** This device was removed from the space: nothing can be sent or read any more, the app must say so. */
    Revoked,

    /** The space uses a protocol version newer than this app: items may be [ItemContent.Unreadable] until it is updated. */
    UpdateRequired,

    /** The relay refuses this device until the user acts for another reason (a format this app can no longer write...). */
    Blocked,

    /**
     * The relay does not find the space or this device ("espace introuvable": a reset relay, a volume that is not mounted...). Not a proof
     * of anything: nothing was erased, and only an explicit "Effacer quand même" erases this device.
     */
    NotFound,
}

/** Who removed a device without a signed decision of the space ([RelayRevocation]). */
enum class RelayRevocationVia {
    /** The relay's administrator. */
    Admin,

    /** The device left on its own, as far as the relay says. */
    Self,

    /** Any other value the core may report in the future: said without a cause. */
    Other,
}

/**
 * A device that the relay alone removed from the space (`take_relay_revocations` of the core). Shown once, as a plain, non-blocking notice, so
 * the user can react if it was not expected. [deviceName] is the device's name, or its id when the name is unknown: never any content.
 */
data class RelayRevocation(val deviceId: String, val deviceName: String, val via: RelayRevocationVia)

/** Common type of the errors a [TomiCore] call may throw (storage, crypto, relay protocol). The pairing errors are [PairingException]. */
open class TomiCoreException(message: String, cause: Throwable? = null) : Exception(message, cause)
