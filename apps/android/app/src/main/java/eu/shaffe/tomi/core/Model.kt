package eu.shaffe.tomi.core

import java.time.Instant

/** Format a text was captured in (wire field `source_format`). It is the default display mode, never a restriction. */
enum class SourceFormat { Plain, Markdown, Html }

/**
 * Text content of an item. [plain] is always present and is the safe fallback;
 * [html] and [markdown] are optional richer representations captured as-is at send time.
 *
 * [sourceFormat] mirrors the `source_format` field of the protocol. When the core does not provide it (older
 * items), it is derived from the representations that are present.
 */
data class RichText(
    val plain: String,
    val html: String? = null,
    val markdown: String? = null,
    val sourceFormat: SourceFormat = when {
        markdown != null -> SourceFormat.Markdown
        html != null -> SourceFormat.Html
        else -> SourceFormat.Plain
    },
) {
    /** Never prints the text: a data class would put every representation in clear into logs and crash reports. */
    override fun toString(): String = "RichText(<redacted>)"
}

/**
 * File attached to an item. [thumbnail] is a small encoded image (PNG/JPEG bytes) generated by the sender.
 * [uri] is only set when the content is available locally (the core resolves it on demand).
 *
 * [slot] is the position the attachment had in the sealed payload when the item was made: STABLE for the life of the item, and what
 * the core is asked for ([TomiCore.attachmentUri], [TomiCore.deleteAttachment]). An attachment removed from the item is no longer in
 * the list while the others keep their slot, so the position in the list is NOT the slot once one was removed. The real core always
 * gives it; null (fixtures, fake core) means "the position in the list", see [slotOf].
 */
class Attachment(
    val name: String,
    val mime: String,
    val size: Long,
    val thumbnail: ByteArray? = null,
    val uri: String? = null,
    val slot: Int? = null,
) {
    val isImage: Boolean get() = mime.startsWith("image/")

    /** The same attachment with an explicit [slot]. */
    fun withSlot(slot: Int): Attachment = Attachment(name, mime, size, thumbnail, uri, slot)

    override fun equals(other: Any?): Boolean {
        if (this === other) return true
        if (other !is Attachment) return false
        return name == other.name && mime == other.mime && size == other.size && slot == other.slot &&
            uri == other.uri && thumbnail.contentEquals(other.thumbnail)
    }

    override fun hashCode(): Int {
        var result = name.hashCode()
        result = 31 * result + mime.hashCode()
        result = 31 * result + size.hashCode()
        result = 31 * result + (slot ?: -1)
        result = 31 * result + (uri?.hashCode() ?: 0)
        result = 31 * result + (thumbnail?.contentHashCode() ?: 0)
        return result
    }
}

/** Slot of the attachment at [index] of this list: its own, or (fixtures, fake core) its position. */
fun List<Attachment>.slotOf(index: Int): Int = this[index].slot ?: index

/** The attachment whose slot is [slot], null when none (never existed, or removed). */
fun List<Attachment>.findBySlot(slot: Int): Attachment? = withIndex().firstOrNull { (index, a) -> (a.slot ?: index) == slot }?.value

/** What [TomiCore.deleteAttachment] did. */
enum class AttachmentRemoval {
    /** The attachment is gone from this device (or everywhere), or already was: the item stays. */
    AttachmentRemoved,

    /** It was the last thing in the item: the whole item was deleted, with the same scope. */
    ItemDeleted,
}

enum class ReadPolicy { Normal, AfterFirstRead }

enum class DeliveryState {
    /** Stored locally, not yet accepted by the relay (offline, or still inside the 3 s undo window). */
    Queued,

    /** Accepted by the relay, not yet fetched by that device. */
    Sent,

    /** Fetched by that device. */
    Delivered,

    /** The item expired before that device could fetch it. */
    ExpiredBeforeDelivery,

    Failed,
}

data class DeviceRef(val id: String, val name: String)

/** Delivery status of an outgoing item for one recipient device. */
data class DeviceDelivery(val deviceId: String, val deviceName: String, val state: DeliveryState)

/** Why an item received from another device cannot be shown. The item is never dropped because of it (DEV.md invariant 7). */
enum class UnreadableReason {
    /** The item uses a protocol or content version this app does not know yet. */
    UpdateRequired,

    /** The item could not be decrypted or decoded. It is kept so that it can be retried after a sync or an update. */
    DecryptionFailed,
}

/** What an item contains, or the reason why it cannot be shown. */
sealed interface ItemContent {
    /** Composite content: every field is optional. */
    data class Readable(
        val title: String? = null,
        val text: RichText? = null,
        val url: String? = null,
        val attachments: List<Attachment> = emptyList(),
        val secret: Boolean = false,
    ) : ItemContent {
        /** Title, text, link and file names are content: never printed (logs, crash reports). Only the shape is. */
        override fun toString(): String = "Readable(secret=$secret, attachments=${attachments.size}, <redacted>)"
    }

    /** The core holds the item but cannot expose its content. */
    data class Unreadable(val reason: UnreadableReason) : ItemContent
}

/**
 * One item of the feed: metadata that is always known, plus [content] which is either [ItemContent.Readable]
 * or [ItemContent.Unreadable]. The shortcuts below return empty values for an unreadable item.
 */
data class TomiItem(
    val id: String,
    val content: ItemContent,
    val sourceDevice: DeviceRef,
    val createdAt: Instant,
    val expiresAt: Instant? = null,
    val readPolicy: ReadPolicy = ReadPolicy.Normal,
    val read: Boolean = false,
    val deliveries: List<DeviceDelivery> = emptyList(),
    /** Pinned on all devices (see spec/pin-contract.md). Default: not pinned. */
    val pinned: Boolean = false,
    /** Time of the decision to pin, used to sort the Pinned section (most recent first); null when not pinned. */
    val pinnedAt: Instant? = null,
    /**
     * Archived on all devices (see spec/archive-contract.md): out of "Recent", still readable and searchable.
     * Never set together with [pinned] by a core (archive unpins, pin unarchives); if both ever arrive, the UI shows the
     * item as pinned. Archiving never changes [read]. Default: not archived.
     */
    val archived: Boolean = false,
    /** Time of the decision to archive; null when not archived. */
    val archivedAt: Instant? = null,
) {
    private val readable: ItemContent.Readable? get() = content as? ItemContent.Readable

    val title: String? get() = readable?.title
    val text: RichText? get() = readable?.text
    val url: String? get() = readable?.url
    val attachments: List<Attachment> get() = readable?.attachments ?: emptyList()
    val secret: Boolean get() = readable?.secret ?: false
    val isReadable: Boolean get() = content is ItemContent.Readable

    /** Never prints the content (title, text, link, file names, devices): logs and crash reports must not carry clear data. */
    override fun toString(): String = "TomiItem(id=$id, secret=$secret, readable=$isReadable, <redacted>)"
}

/** Builds a readable item without spelling out [ItemContent.Readable]. */
fun readableItem(
    id: String,
    sourceDevice: DeviceRef,
    createdAt: Instant,
    title: String? = null,
    text: RichText? = null,
    url: String? = null,
    attachments: List<Attachment> = emptyList(),
    secret: Boolean = false,
    expiresAt: Instant? = null,
    readPolicy: ReadPolicy = ReadPolicy.Normal,
    read: Boolean = false,
    deliveries: List<DeviceDelivery> = emptyList(),
    pinned: Boolean = false,
    pinnedAt: Instant? = null,
    archived: Boolean = false,
    archivedAt: Instant? = null,
): TomiItem = TomiItem(
    id = id,
    content = ItemContent.Readable(title, text, url, attachments, secret),
    sourceDevice = sourceDevice,
    createdAt = createdAt,
    expiresAt = expiresAt,
    readPolicy = readPolicy,
    read = read,
    deliveries = deliveries,
    pinned = pinned,
    pinnedAt = pinnedAt,
    archived = archived,
    archivedAt = archivedAt,
)

fun TomiItem.isOutgoing(localDeviceId: String): Boolean = sourceDevice.id == localDeviceId

/**
 * Whether merely opening the card marks the item read. Never for:
 * - an item already read or sent from this device;
 * - a secret (read only once revealed or copied);
 * - an unreadable item: the user did not see it, and for [ReadPolicy.AfterFirstRead] the core would erase
 *   content that may become readable after an update.
 */
fun TomiItem.shouldMarkReadWhenOpened(localDeviceId: String): Boolean =
    !read && !secret && isReadable && !isOutgoing(localDeviceId)

/** Visual/behavioural category derived from the content. An unreadable item or a secret always wins over the rest. */
enum class ItemKind { Unreadable, Secret, Image, File, Link, RichText, Text }

fun TomiItem.kind(): ItemKind = when {
    !isReadable -> ItemKind.Unreadable
    secret -> ItemKind.Secret
    attachments.isNotEmpty() && attachments.all { it.isImage } -> ItemKind.Image
    attachments.isNotEmpty() -> ItemKind.File
    url != null -> ItemKind.Link
    text?.let { it.html != null || it.markdown != null || it.sourceFormat != SourceFormat.Plain } == true -> ItemKind.RichText
    else -> ItemKind.Text
}

enum class DevicePlatform { Android, Windows, Other }

data class Device(
    val id: String,
    val name: String,
    val platform: DevicePlatform,
    val lastActivity: Instant?,
    val isThisDevice: Boolean,
    /**
     * The core checked the certificate of this device against the chain of the space. `false` for a device that the relay's log lists
     * without a certificate the space accepts: it still shows in the list (it may be revoked), but nothing announces it as joined.
     */
    val verified: Boolean = true,
)

