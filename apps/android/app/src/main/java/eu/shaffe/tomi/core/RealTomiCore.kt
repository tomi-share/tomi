/**
 * [TomiCore] over the Rust core, through the UniFFI bindings (`uniffi.tomi_core`, generated by the build from crates/core/src/ffi.rs).
 *
 * The core does everything that matters: the keys, the PAKE, the encryption, the relay. This class only turns its blocking calls into
 * suspending ones (on [io]), its records into the app's model ([RealCoreMapping]) and its errors into [PairingFailure]
 * ([PairingErrors]). It contains no cryptography and no protocol.
 *
 * Pairing is the part this class is for: [pairWithCode] / [pairWithQr] / [confirmPairing] / [cancelPairing] (the new device),
 * [startInvitation] ([RealInviteSession], the inviting device), [createSpace] (the first device) and [resumePairing] (after a stop).
 * The feed and the devices are forwarded as they are; the files go through [AttachmentProvider] ([attachmentUri]). The departure
 * ([leaveSpace] and the calls after it) runs each blocking attempt to its end and re-reads [departure] afterwards.
 *
 * Secrets: the verification code and the pairing code exist here only as [VerificationCode] / [SensitiveText]; no UniFFI record that
 * carries one is kept, printed or put in a message (a generated data class prints all its fields).
 *
 * @param validDeviceName the rule of the core for a device name (`uniffi.tomi_core.isValidDeviceName`).
 * @param deviceNameCandidates names to try, in order, for this device when it joins a space ([DeviceNames.choose]).
 */
class RealTomiCore(
    private val native: RustTomiCoreInterface,
    private val scope: CoroutineScope,
    private val validDeviceName: (String) -> Boolean,
    private val deviceNameCandidates: () -> List<String?>,
    private val io: CoroutineDispatcher = Dispatchers.IO,
    private val retryDelaysMs: List<Long> = PairingErrors.DEFAULT_RETRY_DELAYS_MS,
    private val resumeBackoffMs: List<Long> = DEFAULT_RESUME_BACKOFF_MS,
    /**
     * The `content://` URI of [AttachmentProvider] for a path of the core's decrypted cache and the MIME type of the attachment (null
     * if unknown); null if the path is not one of them.
     */
    private val attachmentUriOf: (path: String, mime: String?, name: String?) -> String? = { _, _, _ -> null },
    /** The thumbnail the sender puts in an outgoing attachment (blocking, called off the main thread); null for none. */
    private val makeThumbnail: (DraftAttachment) -> DraftThumbnail? = { null },
    /** The configuration of the demo space (called off the main thread, when it is entered); null: no way into the demo. */
    private val demoConfig: (() -> DemoConfig)? = null,
) : TomiCore {
    private val bridge = BlockingBridge(scope, io)

    private val pairedState = MutableStateFlow(false)
    private val demoState = MutableStateFlow(false)
    private val spaceStateFlow = MutableStateFlow(SpaceState.Active)
    private val localDeviceState = MutableStateFlow(UNPAIRED_DEVICE)
    private val departureState = MutableStateFlow<Departure?>(null)

    /** Departure calls in flight (an attempt, or an erasure that waits for one), guarded by [departureCountLock]. */
    private var departureCalls = 0
    private val departureCountLock = Any()
    private val departureRunningState = MutableStateFlow(false)

    /** One tick per change the core announces (feed, devices, transfers, state); the flows below re-read what they show. */
    private val changes = MutableSharedFlow<Unit>(extraBufferCapacity = 1, onBufferOverflow = BufferOverflow.DROP_OLDEST)

    @Volatile
    private var lastItems: List<TomiItem> = emptyList()

    private val joinLock = Any()
    private var join: FfiJoinSession? = null
    private val resumeLock = Mutex()

    /** A re-read of the state is queued: the notifications that come meanwhile are served by it (a sync announces a lot of them). */
    private val stateReadQueued = AtomicBoolean(false)

    init {
        readState()
        native.setListener(
            object : CoreListener {
                override fun onChanged() {
                    // Called from a core thread, with no lock held, and expected to return fast: re-reading happens elsewhere.
                    changes.tryEmit(Unit)
                    if (stateReadQueued.compareAndSet(false, true)) {
                        bridge.inBackground {
                            stateReadQueued.set(false)
                            refreshState()
                        }
                    }
                }
            },
        )
    }

    override val isPaired: StateFlow<Boolean> = pairedState.asStateFlow()
    override val isDemo: StateFlow<Boolean> = demoState.asStateFlow()
    override val spaceState: StateFlow<SpaceState> = spaceStateFlow.asStateFlow()
    override val localDevice: StateFlow<Device> = localDeviceState.asStateFlow()
    override val departure: StateFlow<Departure?> = departureState.asStateFlow()
    override val departureRunning: StateFlow<Boolean> = departureRunningState.asStateFlow()

    override val devices: Flow<List<Device>> = changes.onStart { emit(Unit) }.conflate().map { bridge.quick { readDevices() } }

    override val items: Flow<List<TomiItem>> = changes.onStart { emit(Unit) }.conflate().map { bridge.quick { readItems() } }

    /** A failed re-read keeps what was known: the next change announces a new one. At start-up [readState] is called as it is. */
    private fun refreshState() {
        try {
            readState()
        } catch (_: Exception) {
            // Kept as it was.
        }
    }

    private fun readState() {
        val paired = native.isPaired()
        // Before isPaired: a collector that sees the device paired must already know whether it is the demo.
        demoState.value = native.isDemo()
        pairedState.value = paired
        spaceStateFlow.value = native.spaceState().toDomain()
        departureState.value = native.departure()?.toDomain()
        if (paired) {
            try {
                localDeviceState.value = native.localDevice().toDomain()
            } catch (_: TomiException) {
                // Keep what was known: the next change announces a new read.
            }
        } else {
            localDeviceState.value = UNPAIRED_DEVICE
        }
    }

    private fun readDevices(): List<Device> = try {
        native.devices().filter { it.isMember() }.map { it.toDomain() }
    } catch (_: Exception) {
        emptyList()
    }

    /** A failed read, whatever its cause, keeps the last feed instead of showing an empty one (or crashing the collector). */
    private fun readItems(): List<TomiItem> = try {
        if (native.isPaired()) {
            // What did not change keeps its instance (see reuseUnchanged): the screens skip it.
            reuseUnchanged(lastItems, native.items().mapNotNull { it.toDomain() }).also { lastItems = it }
        } else {
            // Left the space (or never in one): nothing of the old feed may stay, not even as "the last feed that was read".
            lastItems = emptyList()
            emptyList()
        }
    } catch (_: Exception) {
        lastItems
    }

    // --- Feed, forwarded -------------------------------------------------------------------------------------------------------

    override suspend fun getItem(id: String): TomiItem? = coreCall { native.getItem(id)?.toDomain() }

    override suspend fun sync(pushToken: String?) {
        if (!pairedState.value) return
        // The key rotation owed after a departure is the core's own business now (after a sync and from the doorbell loop).
        coreCall { native.sync(pushToken) }
    }

    // --- Real-time channel (doorbell) -------------------------------------------------------------------------------------------

    private val doorbellLock = Any()
    private var doorbellThread: Thread? = null
    private var doorbellStopAsked = false
    private var doorbellWanted = false

    /**
     * Runs the core's doorbell on ONE dedicated thread (`runDoorbell` blocks until [stopLiveSync]). A start that comes while a stopped
     * thread is still draining (it notices within a few seconds) is served by that thread starting over; a doorbell that ends by itself
     * (device revoked, space reset) is not restarted in a loop, only by the next start.
     */
    override fun startLiveSync() {
        if (!pairedState.value) return
        synchronized(doorbellLock) {
            doorbellWanted = true
            if (doorbellThread?.isAlive == true) return
            launchDoorbell()
        }
    }

    override fun stopLiveSync() {
        synchronized(doorbellLock) {
            doorbellWanted = false
            if (doorbellThread?.isAlive != true) return
            doorbellStopAsked = true
            stopDoorbellQuietly()
        }
        insistOnStopping()
    }

    /** The stop is a request to a thread that ends by itself within seconds: a refusal of the core must not end the app (it runs from a collector). */
    private fun stopDoorbellQuietly() {
        try {
            native.stopDoorbell()
        } catch (_: Exception) {
            // The thread notices the stop on its own (repeated by [insistOnStopping]) or the next start takes over.
        }
    }

    /**
     * A stop sent before the loop was entered is not seen by it: it is repeated, a few seconds at most, until the thread has ended or the
     * channel is wanted again. Never call `runDoorbell` from `onChanged`.
     */
    private fun insistOnStopping() {
        scope.launch {
            repeat(STOP_RETRIES) {
                delay(STOP_RETRY_MS)
                synchronized(doorbellLock) {
                    if (doorbellWanted || doorbellThread?.isAlive != true) return@launch
                    stopDoorbellQuietly()
                }
            }
        }
    }

    private fun launchDoorbell() {
        doorbellStopAsked = false
        val thread = Thread({
            try {
                native.runDoorbell()
            } catch (_: Throwable) {
                // The channel is an accelerator: the sync at start-up and the next start still fetch everything. Nothing is logged here on
                // purpose: this file handles the secrets of the pairing (UniffiConfinementTest forbids any log in it).
            }
            synchronized(doorbellLock) {
                doorbellThread = null
                // Stopped on purpose, then wanted again before it noticed: start over. Ended by itself: leave it.
                if (doorbellWanted && doorbellStopAsked) launchDoorbell()
            }
        }, "tomi-doorbell")
        thread.isDaemon = true
        doorbellThread = thread
        thread.start()
    }

    /**
     * With the thumbnails of its images first. If the item is then too large for the relay, it is enqueued again without them (like
     * `fit_payload` on Windows): a preview never costs a send.
     */
    override suspend fun enqueue(draft: OutgoingDraft) {
        coreCall {
            val withThumbnails = draft.toFfi(makeThumbnail)
            try {
                native.enqueue(withThumbnails)
            } catch (e: TomiException.InvalidInput) {
                if (withThumbnails.attachments.none { it.thumbnail != null }) throw e
                native.enqueue(draft.toFfi())
            }
        }
    }

    /** Erases the decrypted copies of the attachments (the encrypted ones stay; [attachmentUri] decrypts again on demand). */
    override suspend fun purgePlaintextCache() = coreCall { native.purgePlaintextCache() }

    override suspend fun dispatch(id: String): DispatchResult = coreCall { native.dispatch(id).toDomain() }

    override suspend fun cancelIfQueued(id: String): Boolean = coreCall { native.cancelIfQueued(id) }

    /**
     * A decision taken here (delete everywhere, read, pin...) leaves through the core's outbox, and only a sync drains it. Without this
     * call it would wait for the next wake or the next launch, and the other devices would not hear of it. Fire and forget: offline,
     * the outbox keeps it and the next sync sends it.
     */
    private fun flushOutbox() {
        scope.launch {
            try {
                sync()
            } catch (e: CancellationException) {
                throw e
            } catch (_: Exception) {
                // Kept in the outbox.
            }
        }
    }

    override suspend fun deleteLocal(id: String) {
        coreCall { native.deleteLocal(id) }
        flushOutbox()
    }

    override suspend fun deleteEverywhere(id: String) {
        coreCall { native.deleteEverywhere(id) }
        flushOutbox()
    }

    override suspend fun markRead(id: String) {
        coreCall { native.markRead(id) }
        flushOutbox()
    }

    /**
     * The core decrypts the file into its cache (downloading it first if needed) and hands back its path; [AttachmentProvider] serves
     * it as a `content://` URI, read-only and without a copy. Null ("unavailable", which the UI handles) when the core has no file or
     * the path is not one of its cache.
     */
    override suspend fun attachmentUri(itemId: String, slot: Int): String? {
        if (slot < 0) return null
        val path = coreCall { native.attachmentPath(itemId, slot.toUInt()) } ?: return null
        val readable = coreCall { native.getItem(itemId) }?.content as? FfiItemContent.Readable
        // The slot, not the position: the list no longer holds the removed attachments.
        val attachment = readable?.attachments?.firstOrNull { it.slot == slot.toUInt() }
        // The receiving app shows the real name, except for a hidden item: its file names stay out of the URI.
        val name = attachment?.name?.takeUnless { readable.secret }
        return attachmentUriOf(path, attachment?.mime, name)
    }

    override suspend fun deleteAttachment(itemId: String, slot: Int, everywhere: Boolean): AttachmentRemoval {
        // A slot is never negative: an impossible one is a no-op like an unknown one (the core is idempotent).
        if (slot < 0) return AttachmentRemoval.AttachmentRemoved
        val result = coreCall { native.deleteAttachment(itemId, slot.toUInt(), everywhere) }
        if (everywhere) flushOutbox()
        return when (result) {
            AttachmentRemovalKind.ATTACHMENT_REMOVED -> AttachmentRemoval.AttachmentRemoved
            AttachmentRemovalKind.ITEM_DELETED -> AttachmentRemoval.ItemDeleted
        }
    }

    override suspend fun supportsAttachmentRemoval(): Boolean = coreCall { native.supportsAttachmentRemoval() }

    override suspend fun renameDevice(id: String, name: String) = coreCall { native.renameDevice(id, name) }

    override suspend fun revokeDevice(id: String) = coreCall { native.revokeDevice(id) }

    // --- Leaving the space (spec/api-v1.md 7.9) ---------------------------------------------------------------------------------

    override suspend fun leaveSpace(): DepartureResult = departureCall { native.leaveSpace() }

    override suspend fun deleteSpace(): DepartureResult = departureCall { native.deleteSpace() }

    override suspend fun retryDeparture(): DepartureResult = departureCall { native.retryDeparture() }

    override suspend fun continueDeparture(): DepartureResult = departureCall { native.continueDeparture() }

    /** One short store transaction in the core: it does not wait for an attempt in progress (whose proof then erases nothing). */
    override suspend fun cancelDeparture(): Boolean {
        val cancelled = try {
            bridge.quick { native.cancelDeparture() }
        } catch (e: CancellationException) {
            throw e
        } catch (_: Exception) {
            false
        }
        withContext(NonCancellable) { bridge.quick { refreshState() } }
        return cancelled
    }

    override suspend fun canEraseWithoutProof(): Boolean = try {
        bridge.quick { native.canEraseWithoutProof() }
    } catch (e: CancellationException) {
        throw e
    } catch (_: Exception) {
        false
    }

    override suspend fun eraseWithoutProof(): EraseResult = running {
        try {
            // Waits for an attempt in progress (the departure lock of the core), then erases; runs to its end whatever the caller does.
            bridge.toTheEnd { native.eraseWithoutProof() }
            EraseResult.Erased
        } catch (e: CancellationException) {
            throw e
        } catch (_: TomiException.InvalidInput) {
            // The verdict that allowed it expired, or another answer replaced it, while the user confirmed. Nothing was erased.
            EraseResult.NotAllowed
        } catch (_: Exception) {
            EraseResult.Failed
        }
    }

    /**
     * One departure attempt of the core, off the caller's thread and to its end even if the caller goes away (a proof that came must be
     * followed by the erasure and the re-read). Every answer of the relay is in the outcome; what the core throws (not provisioned,
     * storage, panic) is [DepartureResult.Failed]: nothing was erased.
     */
    private suspend fun departureCall(block: () -> FfiDepartureOutcome): DepartureResult = running {
        try {
            bridge.toTheEnd(block).toDomain()
        } catch (e: CancellationException) {
            throw e
        } catch (_: Exception) {
            DepartureResult.Failed
        }
    }

    /** Counts [block] in [departureRunning], and re-reads the state when it ends, before the count goes down. */
    private suspend fun <T> running(block: suspend () -> T): T {
        countDepartureCall(+1)
        try {
            return block()
        } finally {
            afterErasure()
            countDepartureCall(-1)
        }
    }

    private fun countDepartureCall(delta: Int) = synchronized(departureCountLock) {
        departureCalls += delta
        departureRunningState.value = departureCalls > 0
    }

    /**
     * After a departure or an erasure, and whatever its outcome: re-reads the state (so that [isPaired] and [departure] say the truth),
     * forgets the last feed when the device is no longer in a space, and tells the collectors to re-read.
     */
    private suspend fun afterErasure() = withContext(NonCancellable) {
        bridge.quick { refreshState() }
        if (!pairedState.value) lastItems = emptyList()
        changes.tryEmit(Unit)
    }

    override suspend fun pin(id: String) {
        coreCall { native.pin(id) }
        flushOutbox()
    }

    override suspend fun unpin(id: String) {
        coreCall { native.unpin(id) }
        flushOutbox()
    }

    override suspend fun archive(id: String) {
        coreCall { native.archive(id) }
        flushOutbox()
    }

    override suspend fun unarchive(id: String) {
        coreCall { native.unarchive(id) }
        flushOutbox()
    }

    private suspend fun <T> coreCall(block: () -> T): T = try {
        bridge.quick(block)
    } catch (e: TomiException) {
        throw PairingErrors.coreException(e)
    }

    // --- Pairing: the new device ---------------------------------------------------------------------------------------------

    override suspend fun pairWithCode(code: String, relayUrl: String?): PairingResult = joinWith(code, relayUrl)

    override suspend fun pairWithQr(payload: String): PairingResult = joinWith(payload, null)

    override suspend fun relayUrl(): String? = coreCall { native.relayUrl() }

    private suspend fun joinWith(codeOrLink: String, relayUrl: String?): PairingResult {
        // A previous attempt that nobody settled is closed first: one pairing at a time, and the relay counts the open channels.
        abandonJoin()

        // The core reports an unreadable code, an invalid device name and "already provisioned" with the same InvalidInput. The last two
        // are settled here, before the call, so that what the call reports is only about the code.
        if (bridge.quick { native.isPaired() }) return alreadyPaired()
        val name = bridge.quick { DeviceNames.choose(deviceNameCandidates(), validDeviceName) }

        val session: FfiJoinSession = try {
            // The claim is one short request. It is not interrupted: a session that came back after a cancellation would leak otherwise.
            bridge.toTheEnd { native.joinSpace(codeOrLink, name, relayUrl) }
        } catch (e: TomiException) {
            return joinRefused(e)
        }
        try {
            currentCoroutineContext().ensureActive()
        } catch (e: CancellationException) {
            bridge.inBackground { cancelAndClose(session) }
            throw e
        }
        synchronized(joinLock) { join = session }

        return try {
            val prompt = bridge.call(onCancel = { cancelAndClose(session) }) {
                PairingErrors.retryingTransient(retryDelaysMs) { session.waitForInviter() }
            }
            awaiting(session, prompt)
        } catch (e: TomiException) {
            dropJoin(session)
            // The code is spent once it was claimed: after a broken connection the user needs a new one, not a retry.
            val reason = PairingErrors.failureOf(e)
            PairingResult.Failure(if (reason == PairingFailure.Network) PairingFailure.Interrupted else reason)
        }
    }

    /**
     * `join_space` refused: [InvalidInput] is an unreadable code or link once the device is unpaired and its name valid. (A relay that was
     * typed is checked by the screen before the call, [RelayAddress.canonical], so it is not what an InvalidInput reports here.)
     */
    private suspend fun joinRefused(e: TomiException): PairingResult {
        if (e !is TomiException.InvalidInput) return PairingResult.Failure(PairingErrors.failureOf(e))
        // A stopped pairing may have been settled (provisioned) between the check and the call.
        if (bridge.quick { native.isPaired() }) return alreadyPaired()
        return PairingResult.Failure(PairingFailure.InvalidCode)
    }

    private suspend fun alreadyPaired(): PairingResult {
        bridge.quick { refreshState() }
        return PairingResult.AlreadyPaired
    }

    /** The prompt of the core as the app's model. The record carries the verification code in a `toString()`: it ends here. */
    private fun awaiting(session: FfiJoinSession, prompt: FfiJoinPrompt): PairingResult.AwaitingVerification =
        PairingResult.AwaitingVerification(
            peer = PairingPeer(prompt.inviter.name, prompt.inviter.platform.toDevicePlatform()),
            verificationCode = VerificationCode(prompt.sas),
            historyItemCount = prompt.history?.items?.toInt()?.coerceAtLeast(0) ?: 0,
            historyBytes = prompt.history?.bytes?.let { if (it > Long.MAX_VALUE.toULong()) Long.MAX_VALUE else it.toLong() } ?: 0L,
            memberCount = prompt.memberCount?.toInt(),
            // A session that the user cancelled in the meantime is already released and refuses the call: nothing is left to count.
            expiresInMs = try {
                session.expiresInMs()
            } catch (_: IllegalStateException) {
                0L
            },
            // The relay of this pairing, to show in full: it may have been read from a QR code or typed (not trusted).
            relayAuthority = prompt.relayAuthority,
        )

    override suspend fun confirmPairing(importHistory: Boolean) {
        val session = synchronized(joinLock) { join } ?: return
        try {
            // The confirmation is deposited first (one request); the key then arrives once the OTHER person confirmed as well, which
            // can take the whole life of the channel. Cancelling the caller, or cancelPairing, ends the wait.
            bridge.quick { session.confirm(importHistory) }
            bridge.call(onCancel = { cancelAndClose(session) }) { PairingErrors.retryingTransient(retryDelaysMs) { session.waitDone() } }
        } catch (e: TomiException) {
            // A transient error or "not the moment" leaves the session alive: the caller may try again, or cancel (which closes it).
            if (!PairingErrors.isTransient(e) && e !is TomiException.InvalidInput) dropJoin(session)
            val reason = PairingErrors.failureOf(e)
            throw PairingException(if (reason == PairingFailure.Network) PairingFailure.Interrupted else reason, e)
        }
        dropJoin(session)
        bridge.quick { refreshState() }
    }

    override suspend fun cancelPairing() = abandonJoin()

    /** Closes the pending pairing at the relay, wipes its secrets and releases the handle. Also unblocks a call that waits on it. */
    private suspend fun abandonJoin() {
        val session = synchronized(joinLock) { join.also { join = null } } ?: return
        withContext(NonCancellable) { bridge.quick { cancelAndClose(session) } }
    }

    /** The session is over (by its own end): forget it and release the handle, as the core asks. */
    private fun dropJoin(session: FfiJoinSession) {
        synchronized(joinLock) { if (join === session) join = null }
        closeQuietly(session)
    }

    private fun cancelAndClose(session: FfiJoinSession) {
        try {
            session.cancel()
        } catch (_: Exception) {
            // Being dropped anyway.
        }
        closeQuietly(session)
    }

    private fun closeQuietly(session: AutoCloseable) {
        try {
            session.close()
        } catch (_: Exception) {
            // Already destroyed.
        }
    }

    // --- Pairing: the inviting device, the first device, the restart ----------------------------------------------------------

    override suspend fun startInvitation(): InviteSession {
        val session = try {
            bridge.toTheEnd { native.startInvitation() }
        } catch (e: TomiException) {
            throw PairingException(PairingErrors.failureOf(e), e)
        }
        val invitation = RealInviteSession(session, bridge, retryDelaysMs)
        try {
            currentCoroutineContext().ensureActive()
        } catch (e: CancellationException) {
            // The channel is open at the relay and the caller will never see this session: close it.
            bridge.inBackground { invitation.abort() }
            throw e
        }
        return invitation
    }

    override suspend fun createSpace(installToken: SensitiveText, deviceName: String, relayUrl: String?) {
        try {
            bridge.quick { native.createSpace(installToken.reveal(), deviceName, relayUrl) }
        } catch (e: TomiException) {
            throw PairingException(PairingErrors.failureOf(e), e)
        }
        bridge.quick { refreshState() }
    }

    /** One settling at a time: the start-up and the pairing screen may both ask. */
    override suspend fun resumePairing(): ResumeOutcome = resumeLock.withLock { settlePending() }

    private suspend fun settlePending(): ResumeOutcome {
        var attempt = 0
        while (true) {
            try {
                val kind = bridge.quick {
                    if (native.isPaired() || !native.hasPendingPairing()) ResumeKind.NOTHING else native.resumePairing()
                }
                return when (kind) {
                    ResumeKind.NOTHING -> ResumeOutcome.NothingPending
                    ResumeKind.PROVISIONED -> {
                        bridge.quick { refreshState() }
                        ResumeOutcome.Provisioned
                    }
                    ResumeKind.DISCARDED -> ResumeOutcome.Discarded
                }
            } catch (e: TomiException) {
                // The relay could not be asked (offline...): try again a few times, then leave it to the next start.
                if (!PairingErrors.isTransient(e) || attempt >= resumeBackoffMs.size) return ResumeOutcome.Unreachable
                delay(resumeBackoffMs[attempt++])
            }
        }
    }

    // --- Demo ------------------------------------------------------------------------------------------------------------------

    override fun supportsDemoEntry(): Boolean = demoConfig != null && native.supportsDemoEntry()

    /** The core opens the demo space (seconds, about 45 MB written): it runs to its end even if the caller goes away. */
    override suspend fun enterDemo() {
        val config = demoConfig ?: throw TomiCoreException("core: no demo")
        // One pairing at a time: the core refuses the demo while one is pending.
        abandonJoin()
        try {
            bridge.toTheEnd { native.enterDemo(config()) }
        } catch (e: TomiException) {
            throw PairingErrors.coreException(e)
        }
        bridge.quick { refreshState() }
        changes.tryEmit(Unit)
    }

    /** Back to the real core, unpaired: the state is re-read and the demo feed forgotten ([afterErasure]). */
    override suspend fun leaveDemo() {
        bridge.quick { native.leaveDemo() }
        afterErasure()
    }

    override fun isValidDeviceName(name: String): Boolean = validDeviceName(name)

    companion object {
        /** Between two tries of [resumePairing] while the relay cannot be reached: about two minutes in all. */
        val DEFAULT_RESUME_BACKOFF_MS: List<Long> = listOf(2_000L, 5_000L, 15_000L, 30_000L, 60_000L)

        /** The stop is repeated every 200 ms, 25 times (5 s: the longest the core takes to notice it). */
        private const val STOP_RETRY_MS = 200L
        private const val STOP_RETRIES = 25

        /** What the UI shows as this device until the core has one (it answers only once provisioned). */
        private val UNPAIRED_DEVICE =
            Device(id = "", name = DeviceNames.FALLBACK, platform = DevicePlatform.Android, lastActivity = null, isThisDevice = true)
    }
