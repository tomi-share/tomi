#!/usr/bin/env python3
"""Generates Packages/TomiDesign/Sources/TomiDesign/TomiTokens.swift from design/tomi/tokens.json.

The design tokens have one source of truth (design/tomi/tokens.json, charter in
design/tomi/brand-guidelines.md); this script turns them into Swift constants so the Apple apps
never copy a value by hand. Run it again after any change of the tokens (the output is
deterministic: running it twice changes nothing).

Naming: a token `a.b.c-d` becomes `TomiTokens.AB.cD` (group = every segment but the last, in
UpperCamelCase; name = last segment in lowerCamelCase, prefixed with `step` when it starts
with a digit). Colours (`#RRGGBB`) become `UInt32` literals `0xRRGGBB`.

Usage: python3 -I apps/apple/tools/tokens-to-swift.py
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / "design/tomi/tokens.json"
OUTPUT = ROOT / "apps/apple/Packages/TomiDesign/Sources/TomiDesign/TomiTokens.swift"


def camel(segment: str, upper: bool) -> str:
    words = [w for w in re.split(r"[-_]", segment) if w]
    out = "".join(w[:1].upper() + w[1:] for w in words)
    if not upper:
        out = out[:1].lower() + out[1:]
    return out


def swift_literal(value):
    if isinstance(value, bool):
        return "Bool", "true" if value else "false"
    if isinstance(value, int):
        return "Int", str(value)
    if isinstance(value, float):
        return "Double", repr(value)
    if isinstance(value, str) and re.fullmatch(r"#[0-9A-Fa-f]{6}", value):
        return "UInt32", "0x" + value[1:].upper()
    if isinstance(value, str):
        return "String", json.dumps(value, ensure_ascii=False)
    raise ValueError(f"unsupported token value: {value!r}")


def main() -> int:
    tokens = json.loads(SOURCE.read_text(encoding="utf-8"))
    groups: dict[str, list[tuple[str, str, str, str]]] = {}
    for key, token in tokens.items():
        if key.startswith("_"):
            continue
        parts = key.split(".")
        group = "".join(camel(p, upper=True) for p in parts[:-1])
        name = camel(parts[-1], upper=False)
        if name[:1].isdigit():
            name = "step" + name
        typ, literal = swift_literal(token["value"])
        comment = " ".join(str(token.get("comment", "")).split())
        groups.setdefault(group, []).append((name, typ, literal, comment))

    lines = [
        "// GENERATED by apps/apple/tools/tokens-to-swift.py from design/tomi/tokens.json — do not edit.",
        "",
        "/// Raw values of the Tomi design tokens. Colours are `0xRRGGBB`; sizes are points (the px of",
        "/// Windows and the dp / sp of Android). Use them through `TomiTheme`, not directly in views.",
        "public enum TomiTokens {",
    ]
    for group in sorted(groups):
        lines.append(f"    public enum {group} {{")
        for name, typ, literal, comment in groups[group]:
            if comment:
                lines.append(f"        /// {comment}")
            lines.append(f"        public static let {name}: {typ} = {literal}")
        lines.append("    }")
    lines.append("}")
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
