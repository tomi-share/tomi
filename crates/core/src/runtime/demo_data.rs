/// The whole demo feed at `scale`, in any order (the demo writes it oldest first).
pub(crate) fn entries(scale: Scale) -> Vec<DemoEntry> {
    let mut all = android_entries();
    all.extend(super::demo_history::validation_week(scale));
    all.extend(super::demo_history::history(scale));
    all
}

