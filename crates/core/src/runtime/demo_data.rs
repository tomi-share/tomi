//! Content of the demo space (`runtime::demo`).
//!
//! The feed has three parts, written oldest first by the demo:
//! - the 23 most recent items, item for item the demo feed of the Android app
//!   (`apps/android/.../core/FakeTomiCore.kt`), so that every client shows the same top of feed;
//! - a "validation week" ([`super::demo_history::validation_week`]): over the last seven days,
//!   items of every kind the apps can show, with heavy generated attachments;
//! - about three years of ordinary history ([`super::demo_history::history`]), generated
//!   deterministically, so that the demo also measures the apps on a long feed.
//!
//! Binary files of the Android part (images, code files) are read from the `assets_dir` given
//! by the app (Android keeps them in `app/src/debug/assets/demo/`); when one is missing a small
//! built-in stand-in is used instead, so the demo never fails for a missing asset. Every other
//! file is generated by the core ([`super::demo_files`]).

use std::borrow::Cow;

use super::demo_files::Generated;
use crate::item::SourceFormat;

pub(crate) const MINUTE: i64 = 60_000;
pub(crate) const HOUR: i64 = 60 * MINUTE;
pub(crate) const DAY: i64 = 24 * HOUR;

/// Text of the demo: written in the source, or generated.
pub(crate) type Str = Cow<'static, str>;

/// A text written in the source.
pub(crate) const fn st(text: &'static str) -> Str {
    Cow::Borrowed(text)
}

/// An optional text written in the source.
pub(crate) const fn s(text: &'static str) -> Option<Str> {
    Some(Cow::Borrowed(text))
}

/// How big the demo is. The tests open it many times, unoptimised: they get a short history
/// and small files, the same kinds of items.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Scale {
    Full,
    Test,
}

impl Scale {
    /// The scale of this build ([`Scale::Test`] in the tests of the crate).
    pub(crate) const DEFAULT: Self = if cfg!(test) { Self::Test } else { Self::Full };

    /// `full` in the full demo, `test` in the tests.
    pub(crate) const fn pick(self, full: u32, test: u32) -> u32 {
        match self {
            Self::Full => full,
            Self::Test => test,
        }
    }
}

/// Device that writes a demo item.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Author {
    /// "PC-Bureau" (Windows), also the founder of the demo space.
    Office,
    /// "PC-Maison" (Windows).
    Home,
    /// This device, in the past (items "sent from this phone").
    This,
}

/// A file attached to a demo item.
#[derive(Debug, Clone)]
pub(crate) enum DemoFile {
    /// Bundled demo file of the app, by name (image or code file).
    Asset {
        name: &'static str,
        mime: &'static str,
    },
    /// One-page PDF generated on the fly (ASCII `title` printed on it).
    Pdf { name: Str, title: Str },
    /// Small text file.
    Text { name: Str, mime: Str, content: Str },
    /// File generated at the opening ([`Generated`]).
    Generated { name: Str, file: Generated },
}

#[derive(Debug, Clone)]
pub(crate) struct DemoText {
    pub plain: Str,
    pub markdown: Option<Str>,
    pub html: Option<Str>,
    pub source_format: SourceFormat,
}

pub(crate) const fn plain(text: &'static str) -> Option<DemoText> {
    Some(DemoText {
        plain: st(text),
        markdown: None,
        html: None,
        source_format: SourceFormat::Plain,
    })
}

/// One item of the demo feed.
#[derive(Debug, Clone)]
pub(crate) struct DemoEntry {
    /// Short stable name (tests, debugging); never shown.
    pub key: Str,
    /// How long ago it was written.
    pub age_ms: i64,
    pub from: Author,
    pub title: Option<Str>,
    pub text: Option<DemoText>,
    pub url: Option<Str>,
    pub files: Vec<DemoFile>,
    pub secret: bool,
    pub after_first_read: bool,
    /// Expiration chosen by the sender, counted from the creation.
    pub expires_after_ms: Option<i64>,
    /// Already read on this device.
    pub read: bool,
    pub pinned: bool,
    pub archived: bool,
    /// Sealed in a format this app does not know yet ("update required").
    pub unreadable: bool,
    /// PC-Maison catches up right after this item (its receipts make the item "delivered
    /// to all" while later items stay "sent" to it).
    pub home_catches_up: bool,
}

