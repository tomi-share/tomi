/// What the feed of a demo joined with its history holds (the tests of the crate check the
/// engine against it).
#[cfg(test)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct FeedCounts {
    pub items: usize,
    pub archived: usize,
    pub pinned: usize,
}

/// Counts of the feed at `scale`: nothing in it is consumed or expired at the opening.
#[cfg(test)]
pub(crate) fn counts(scale: Scale) -> FeedCounts {
    let all = entries(scale);
    FeedCounts {
        items: all.len(),
        archived: all.iter().filter(|e| e.archived).count(),
        pinned: all.iter().filter(|e| e.pinned).count(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_top_of_the_feed_mirrors_the_android_demo() {
        let all = android_entries();
        assert_eq!(all.len(), 23);
        assert_eq!(all.iter().filter(|e| e.archived).count(), 4);
        assert_eq!(all.iter().filter(|e| e.pinned).count(), 2);
        assert_eq!(all.iter().filter(|e| e.from == Author::This).count(), 2);
        assert!(
            all.iter().all(|e| e.age_ms < 30 * DAY),
            "within the relay retention"
        );
        // The item PC-Maison catches up after is older than every other item sent from here.
        let catch_up = all.iter().find(|e| e.home_catches_up).map(|e| e.age_ms);
        assert!(all
            .iter()
            .filter(|e| e.from == Author::This && !e.home_catches_up)
            .all(|e| Some(e.age_ms) < catch_up));
    }

    fn check_feed(scale: Scale) -> Vec<DemoEntry> {
        let all = entries(scale);
        let mut keys: Vec<_> = all.iter().map(|e| e.key.clone()).collect();
        keys.sort_unstable();
        keys.dedup();
        assert_eq!(keys.len(), all.len(), "unique keys");
        assert_eq!(all.iter().filter(|e| e.home_catches_up).count(), 1);
        for e in &all {
            // Reading it at the junction would consume it: never in the feed.
            assert!(
                !(e.after_first_read && e.read && e.from != Author::This),
                "{} would be consumed",
                e.key
            );
            assert!(!(e.pinned && e.archived), "{}", e.key);
            assert!(
                e.expires_after_ms.is_none_or(|x| x > e.age_ms + HOUR / 2),
                "{} expires too soon",
                e.key
            );
            assert!(!e.after_first_read || e.secret, "{}", e.key);
            let text = e.text.as_ref().map_or(0, |t| {
                t.plain.len()
                    + t.markdown.as_ref().map_or(0, |m| m.len())
                    + t.html.as_ref().map_or(0, |h| h.len())
            });
            // The payload (texts and thumbnails, in JSON) is 1 MiB at most.
            assert!(text < 700_000, "{} is too long ({text})", e.key);
        }
        all
    }

    #[test]
    fn the_test_feed_is_small_and_consistent() {
        let all = check_feed(Scale::Test);
        assert!(all.len() < 150, "{}", all.len());
        assert_eq!(counts(Scale::Test).items, all.len());
    }

    #[test]
    fn the_full_feed_spans_three_years_of_daily_use() {
        let all = check_feed(Scale::Full);
        assert!((2_900..3_300).contains(&all.len()), "{}", all.len());
        let oldest = all.iter().map(|e| e.age_ms).max().unwrap();
        assert!(oldest > 1_000 * DAY && oldest <= 3 * 365 * DAY + DAY);
        let c = counts(Scale::Full);
        assert!(c.archived > 500 && c.pinned >= 4, "{c:?}");
        // Mostly read, mostly links and texts.
        assert!(all.iter().filter(|e| !e.read).count() < all.len() / 20);
        let links = all.iter().filter(|e| e.url.is_some()).count();
        let texts = all.iter().filter(|e| e.text.is_some()).count();
        assert!(links + texts > all.len() * 3 / 4);
        for from in [Author::Office, Author::Home, Author::This] {
            assert!(all.iter().filter(|e| e.from == from).count() > 300);
        }
    }

    #[test]
    fn the_validation_week_covers_every_kind_of_item() {
        let week = super::super::demo_history::validation_week(Scale::Full);
        assert!((40..=60).contains(&week.len()), "{}", week.len());
        assert!(week.iter().all(|e| e.age_ms <= 7 * DAY));
        let mimes: Vec<&str> = week
            .iter()
            .flat_map(|e| &e.files)
            .filter_map(|f| match f {
                DemoFile::Generated { file, .. } => Some(file.mime()),
                _ => None,
            })
            .collect();
        for mime in [
            "image/bmp",
            "application/pdf",
            "text/csv",
            "application/json",
            "text/plain",
            "text/x-rust",
            "text/x-kotlin",
            "text/x-python",
            "audio/wav",
            "application/zip",
            "text/markdown",
            "application/octet-stream",
        ] {
            assert!(mimes.contains(&mime), "no {mime}");
        }
        let has = |f: &dyn Fn(&DemoEntry) -> bool| week.iter().any(f);
        assert!(has(&|e| e.unreadable));
        assert!(has(&|e| e.pinned));
        assert!(has(&|e| e.archived));
        assert!(has(&|e| !e.read));
        assert!(has(&|e| e.from == Author::This));
        assert!(has(&|e| e.secret && e.after_first_read));
        assert!(has(&|e| e.files.len() >= 4));
        assert!(has(&|e| e.text.as_ref().is_some_and(|t| t.html.is_some())));
        assert!(has(&|e| e
            .text
            .as_ref()
            .and_then(|t| t.markdown.as_ref())
            .is_some_and(|m| m.len() >= 100_000)));
        for after in [HOUR, DAY, 7 * DAY, 30 * DAY] {
            assert!(has(&|e| e.expires_after_ms == Some(after)), "{after}");
        }
    }
}
