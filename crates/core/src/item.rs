//! Composite item model and its v1 JSON payload encoding (spec §5.4).
//!
//! Everything here travels **inside** the ciphertext. The JSON field names are part of
//! the format; the Rust names are not.

use std::collections::HashSet;
use std::fmt;

use base64::engine::general_purpose::STANDARD as B64;
use base64::Engine as _;
use serde::de::{self, Deserializer, MapAccess, SeqAccess, Visitor};
use serde::{Deserialize, Serialize};
use zeroize::Zeroizing;

use crate::crypto::{parse_uuid, KEY_LEN, NONCE_PREFIX_LEN};
use crate::error::{CoreError, Result};

/// How long the item lives on devices once read (spec §5.4.2).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ReadPolicy {
    /// Kept until `expires_at` (or forever if absent).
    UntilExpiry,
    /// Deleted after the first explicit reveal/copy. Only on explicit user choice, never a
    /// default, secrets included (PROJECT.md §7, decision D1).
    AfterFirstRead,
}

impl ReadPolicy {
    fn as_wire(self) -> &'static str {
        match self {
            ReadPolicy::UntilExpiry => "until_expiry",
            ReadPolicy::AfterFirstRead => "after_first_read",
        }
    }
    /// Unknown values map to the most restrictive policy (spec §5.4.2).
    fn from_wire(s: Option<&str>) -> Self {
        match s {
            None | Some("until_expiry") => ReadPolicy::UntilExpiry,
            Some(_) => ReadPolicy::AfterFirstRead,
        }
    }
}

/// Representation detected at capture, only a display default (PROJECT.md §1).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SourceFormat {
    Plain,
    Markdown,
    Html,
}

impl SourceFormat {
    fn as_wire(self) -> &'static str {
        match self {
            SourceFormat::Plain => "plain",
            SourceFormat::Markdown => "markdown",
            SourceFormat::Html => "html",
        }
    }
    /// Unknown values fall back to `plain`.
    fn from_wire(s: Option<&str>) -> Self {
        match s {
            Some("markdown") => SourceFormat::Markdown,
            Some("html") => SourceFormat::Html,
            _ => SourceFormat::Plain,
        }
    }
}

/// Text representations captured together.
#[derive(Clone, PartialEq, Eq)]
pub struct ItemText {
    /// Plain text; always present, used as fallback.
    pub plain: String,
    /// Raw HTML as captured (sanitised only at render time).
    pub html: Option<String>,
    /// Markdown representation, if any.
    pub markdown: Option<String>,
    /// Display default.
    pub source_format: SourceFormat,
}

/// Small preview generated by the sender (D20).
#[derive(Clone, PartialEq, Eq)]
pub struct Thumbnail {
    pub mime: String,
    pub data: Vec<u8>,
}

/// Reference to an encrypted attachment blob (spec §6).
#[derive(Clone, PartialEq, Eq)]
pub struct Attachment {
    /// Relay identifier of the encrypted blob (UUID).
    pub blob_id: String,
    /// Original file name (never visible to the relay).
    pub name: String,
    /// MIME type.
    pub mime: String,
    /// Plaintext size in bytes.
    pub size: u64,
    /// 32-byte random file key (STREAM key).
    pub file_key: Vec<u8>,
    /// 19-byte random STREAM nonce prefix.
    pub nonce_prefix: Vec<u8>,
    /// Optional preview.
    pub thumbnail: Option<Thumbnail>,
}

/// Payload JSON of an item exactly as it was received or read back from storage.
///
/// Spec §5.4.4: a device that re-seals an item locally (§7.2) or exports it in a history
/// transfer (§8.7.3) must not lose the fields it does not know (an additive field written
/// by a newer device, such as the reserved `audience` of §5.8.1). The core therefore keeps
/// the original bytes next to the parsed fields and writes them back unchanged. Only the
/// core creates it (parsing); callers can read it or drop it, never forge it.
#[derive(Clone)]
pub struct RawPayload(Zeroizing<Vec<u8>>);

impl RawPayload {
    fn new(json: &[u8]) -> Self {
        Self(Zeroizing::new(json.to_vec()))
    }

    /// The payload JSON (UTF-8, unpadded), byte for byte as received.
    pub fn as_bytes(&self) -> &[u8] {
        &self.0
    }
}

// Never prints the content (DEV.md invariant 3).
impl fmt::Debug for RawPayload {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("RawPayload(<redacted>)")
    }
}

/// Composite item: any combination of title, text, URL and files.
///
/// Two items are equal when their v1 fields are equal; [`Item::raw_payload`] is a transport
/// detail and is not compared.
#[derive(Clone)]
pub struct Item {
    /// Item id (UUID, lowercase hyphenated). Also in the envelope header and the AAD.
    pub id: String,
    /// Device id (32 lowercase hex chars) of the sender.
    pub source_device: String,
    /// Creation time, milliseconds since the Unix epoch (UTC).
    pub created_at_ms: i64,
    /// Expiration chosen by the user (ms since epoch), `None` = never (the default, secrets
    /// included). Drives local erasure only; the relay retention deadline is computed
    /// separately by [`crate::relay_expires_at_ms`] (spec §5.7).
    pub expires_at_ms: Option<i64>,
    pub read_policy: ReadPolicy,
    /// Secret flag: hidden by default, sensitive clipboard (DEV.md invariant 4).
    pub secret: bool,
    /// Title. For a secret item the title **is part of the secret** (spec §5.4.5): it is
    /// only shown together with the revealed content and never indexed for search. Use
    /// [`Item::visible_title`] for anything shown without an explicit reveal.
    pub title: Option<String>,
    pub text: Option<ItemText>,
    pub url: Option<String>,
    pub attachments: Vec<Attachment>,
    /// Original payload bytes, set when the item was parsed (received, read from local
    /// storage, imported from a history transfer) and `None` for an item built by the
    /// application. When present, [`LocalKey::seal_item`](crate::LocalKey::seal_item),
    /// [`seal_item`](crate::seal_item) and the history export write it back **unchanged**,
    /// so unknown fields at any depth survive (spec §5.4.4). It is only valid while the
    /// fields above still describe it: sealing an item whose fields were edited fails with
    /// `invalid_input`; set this to `None` to deliberately rewrite the payload from the
    /// known fields (unknown fields are then dropped).
    pub raw_payload: Option<RawPayload>,
}

impl PartialEq for Item {
    fn eq(&self, other: &Self) -> bool {
        // Destructured so that a new field cannot be forgotten here.
        let Item {
            id,
            source_device,
            created_at_ms,
            expires_at_ms,
            read_policy,
            secret,
            title,
            text,
            url,
            attachments,
            raw_payload: _,
        } = self;
        *id == other.id
            && *source_device == other.source_device
            && *created_at_ms == other.created_at_ms
            && *expires_at_ms == other.expires_at_ms
            && *read_policy == other.read_policy
            && *secret == other.secret
            && *title == other.title
            && *text == other.text
            && *url == other.url
            && *attachments == other.attachments
    }
}

impl Eq for Item {}

