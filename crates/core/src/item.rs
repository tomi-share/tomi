// ---------------------------------------------------------------------------
// Wire (JSON) representation. Unknown fields are ignored for the logic (no
// deny_unknown_fields) but kept in `Item::raw_payload`, which is what gets re-sealed and
// exported (spec §5.4.4). Duplicate keys are rejected at every depth, known or not, by
// `reject_duplicate_keys` before this representation is parsed (spec §5.4).
//
// `audience` is a RESERVED root field (spec §5.8.1): a v1 reader ignores it whatever its
// value, and a v1 writer never emits it. Do not declare it here before a version of the
// spec defines its semantics: parsing or validating it would make this reader diverge
// from the v1 readers already deployed.
// ---------------------------------------------------------------------------

#[derive(Serialize, Deserialize)]
struct WireItem {
    id: String,
    source_device: String,
    created_at: i64,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    expires_at: Option<i64>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    read_policy: Option<String>,
    #[serde(default)]
    secret: bool,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    title: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    text: Option<WireText>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    url: Option<String>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    attachments: Vec<WireAttachment>,
}

#[derive(Serialize, Deserialize)]
struct WireText {
    plain: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    html: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    markdown: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    source_format: Option<String>,
}

#[derive(Serialize, Deserialize)]
struct WireAttachment {
    blob_id: String,
    name: String,
    mime: String,
    size: u64,
    key: String,
    nonce_prefix: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    thumbnail: Option<WireThumbnail>,
}

#[derive(Serialize, Deserialize)]
struct WireThumbnail {
    mime: String,
    data: String,
}

/// Checks a device id: exactly 32 lowercase hex characters.
pub(crate) fn validate_device_id(s: &str) -> bool {
    s.len() == 32 && s.bytes().all(|c| matches!(c, b'0'..=b'9' | b'a'..=b'f'))
}

pub(crate) fn b64_decode(s: &str, what: &str) -> Result<Vec<u8>> {
    B64.decode(s)
        .map_err(|_| CoreError::payload(format!("{what}: invalid base64")))
}

impl Item {
    /// Checks the invariants of a v1 item (used before sealing).
    pub(crate) fn validate(&self) -> Result<()> {
        parse_uuid(&self.id, "item id")?;
        if !validate_device_id(&self.source_device) {
            return Err(CoreError::input("source_device: expected 32 lowercase hex"));
        }
        for (i, a) in self.attachments.iter().enumerate() {
            parse_uuid(&a.blob_id, "blob_id")?;
            if a.file_key.len() != KEY_LEN {
                return Err(CoreError::input(format!("attachment {i}: file_key length")));
            }
            if a.nonce_prefix.len() != NONCE_PREFIX_LEN {
                return Err(CoreError::input(format!(
                    "attachment {i}: nonce_prefix length"
                )));
            }
        }
        if u32::try_from(self.attachments.len()).is_err() {
            return Err(CoreError::input("too many attachments"));
        }
        Ok(())
    }

    /// Title that may be shown without an explicit reveal (feed card, notification, list of
    /// recent items): `None` for a secret, whose title is part of the secret (spec §5.4.5).
    pub fn visible_title(&self) -> Option<&str> {
        if self.secret {
            None
        } else {
            self.title.as_deref()
        }
    }

    /// Text a client may put in its local search index: title, plain text, URL and file
    /// names, separated by `\n`. `None` for a secret: neither its content nor its title is
    /// ever indexed (spec §5.4.5).
    pub fn searchable_text(&self) -> Option<String> {
        if self.secret {
            return None;
        }
        let mut parts: Vec<&str> = Vec::new();
        parts.extend(self.title.as_deref());
        parts.extend(self.text.as_ref().map(|t| t.plain.as_str()));
        parts.extend(self.url.as_deref());
        parts.extend(self.attachments.iter().map(|a| a.name.as_str()));
        Some(parts.join("\n"))
    }

    /// The v1 JSON payload to seal or export (UTF-8, unpadded): the original bytes if the
    /// item was parsed and not edited since, otherwise a serialization of the known fields.
    pub(crate) fn to_json(&self) -> Result<Vec<u8>> {
        self.validate()?;
        let Some(raw) = &self.raw_payload else {
            return self.to_known_json();
        };
        // The preserved bytes stand for this item only while they still describe it.
        let still_describes_item =
            Self::parse_known(raw.as_bytes(), Some(&self.id)).is_ok_and(|parsed| parsed == *self);
        if !still_describes_item {
            return Err(CoreError::input(
                "item edited since it was parsed: set raw_payload to None to rewrite its payload",
            ));
        }
        Ok(raw.as_bytes().to_vec())
    }

    /// Slots whose entry carries `"removed": true` in the payload (spec §8.10.4): removed
    /// attachments that kept their place. Read from the original bytes (the field is
    /// additive and not part of [`Attachment`]); empty for an item built by the application.
    #[cfg_attr(not(feature = "runtime"), allow(dead_code))]
    pub(crate) fn removed_slots(&self) -> Vec<u32> {
        let Some(raw) = &self.raw_payload else {
            return Vec::new();
        };
        #[derive(Deserialize)]
        struct Probe {
            #[serde(default)]
            attachments: Vec<ProbeEntry>,
        }
        #[derive(Deserialize)]
        struct ProbeEntry {
            #[serde(default)]
            removed: bool,
        }
        let Ok(probe) = serde_json::from_slice::<Probe>(raw.as_bytes()) else {
            return Vec::new();
        };
        probe
            .attachments
            .iter()
            .enumerate()
            .filter(|(_, e)| e.removed)
            .filter_map(|(i, _)| u32::try_from(i).ok())
            .collect()
    }

    /// The same item with attachment `slot` emptied as if it had never existed (spec §8.10.4):
    /// the entry keeps its place and its `blob_id` (to check later removals against) but loses
    /// its name, type, size, key, nonce prefix, thumbnail and every other field; it is
    /// marked `"removed": true`. The neutral values (empty name and type, size 0, 32 and 19
    /// zero bytes) are valid for a reader that does not know the marker. Every other field of
    /// the payload, known or not, is kept. `Ok(None)` if the slot does not exist.
    #[cfg_attr(not(feature = "runtime"), allow(dead_code))]
    pub(crate) fn with_attachment_emptied(&self, slot: u32) -> Result<Option<Item>> {
        let Some(att) = self.attachments.get(slot as usize) else {
            return Ok(None);
        };
        let base = match &self.raw_payload {
            Some(raw) => raw.as_bytes().to_vec(),
            None => self.to_known_json()?,
        };
        let mut root: serde_json::Value = serde_json::from_slice(&base)
            .map_err(|e| CoreError::payload(format!("json: {}", json_category(&e))))?;
        let entry = root
            .get_mut("attachments")
            .and_then(|a| a.get_mut(slot as usize))
            .ok_or_else(|| CoreError::payload("attachments: missing entry"))?;
        *entry = serde_json::json!({
            "blob_id": att.blob_id,
            "name": "",
            "mime": "",
            "size": 0,
            "key": B64.encode([0u8; KEY_LEN]),
            "nonce_prefix": B64.encode([0u8; NONCE_PREFIX_LEN]),
            "removed": true,
        });
        let json = Zeroizing::new(serde_json::to_vec(&root).map_err(|_| CoreError::Internal {
            reason: "json serialization failed".into(),
        })?);
        Self::parse_json(&json, Some(&self.id)).map(Some)
    }

    /// Serializes the known fields only. Field order is not normative.
    fn to_known_json(&self) -> Result<Vec<u8>> {
        let wire = WireItem {
            id: self.id.clone(),
            source_device: self.source_device.clone(),
            created_at: self.created_at_ms,
            expires_at: self.expires_at_ms,
            read_policy: Some(self.read_policy.as_wire().to_owned()),
            secret: self.secret,
            title: self.title.clone(),
            text: self.text.as_ref().map(|t| WireText {
                plain: t.plain.clone(),
                html: t.html.clone(),
                markdown: t.markdown.clone(),
                source_format: Some(t.source_format.as_wire().to_owned()),
            }),
            url: self.url.clone(),
            attachments: self
                .attachments
                .iter()
                .map(|a| WireAttachment {
                    blob_id: a.blob_id.clone(),
                    name: a.name.clone(),
                    mime: a.mime.clone(),
                    size: a.size,
                    key: B64.encode(&a.file_key),
                    nonce_prefix: B64.encode(&a.nonce_prefix),
                    thumbnail: a.thumbnail.as_ref().map(|t| WireThumbnail {
                        mime: t.mime.clone(),
                        data: B64.encode(&t.data),
                    }),
                })
                .collect(),
        };
        serde_json::to_vec(&wire).map_err(|_| CoreError::Internal {
            reason: "json serialization failed".into(),
        })
    }

    /// Parses a v1 JSON payload (spec §5.4). `expected_id` comes from the envelope header.
    pub(crate) fn from_json(json: &[u8], expected_id: &str) -> Result<Self> {
        Self::parse_json(json, Some(expected_id))
    }

    /// Parses a v1 JSON payload whose id is not announced elsewhere (history index,
    /// local records). Same rules as [`Item::from_json`] otherwise.
    pub(crate) fn from_json_unchecked_id(json: &[u8]) -> Result<Self> {
        Self::parse_json(json, None)
    }

    fn parse_json(json: &[u8], expected_id: Option<&str>) -> Result<Self> {
        let mut item = Self::parse_known(json, expected_id)?;
        item.raw_payload = Some(RawPayload::new(json));
        Ok(item)
    }

    /// Parses and validates the payload; the result carries no `raw_payload`.
    fn parse_known(json: &[u8], expected_id: Option<&str>) -> Result<Self> {
        reject_duplicate_keys(json)?;
        let wire: WireItem = serde_json::from_slice(json)
            .map_err(|e| CoreError::payload(format!("json: {}", json_category(&e))))?;
        if parse_uuid(&wire.id, "id").is_err() {
            return Err(CoreError::payload("id: not a canonical UUID"));
        }
        if expected_id.is_some_and(|id| wire.id != id) {
            return Err(CoreError::ItemIdMismatch);
        }
        if !validate_device_id(&wire.source_device) {
            return Err(CoreError::payload(
                "source_device: expected 32 lowercase hex",
            ));
        }
        let mut attachments = Vec::with_capacity(wire.attachments.len());
        for a in wire.attachments {
            if parse_uuid(&a.blob_id, "blob_id").is_err() {
                return Err(CoreError::payload("blob_id: not a canonical UUID"));
            }
            let file_key = b64_decode(&a.key, "key")?;
            if file_key.len() != KEY_LEN {
                return Err(CoreError::payload("key: expected 32 bytes"));
            }
            let nonce_prefix = b64_decode(&a.nonce_prefix, "nonce_prefix")?;
            if nonce_prefix.len() != NONCE_PREFIX_LEN {
                return Err(CoreError::payload("nonce_prefix: expected 19 bytes"));
            }
            let thumbnail = match a.thumbnail {
                Some(t) => Some(Thumbnail {
                    mime: t.mime,
                    data: b64_decode(&t.data, "thumbnail")?,
                }),
                None => None,
            };
            attachments.push(Attachment {
                blob_id: a.blob_id,
                name: a.name,
                mime: a.mime,
                size: a.size,
                file_key,
                nonce_prefix,
                thumbnail,
            });
        }
        Ok(Item {
            id: wire.id,
            source_device: wire.source_device,
            created_at_ms: wire.created_at,
            expires_at_ms: wire.expires_at,
            read_policy: ReadPolicy::from_wire(wire.read_policy.as_deref()),
            secret: wire.secret,
            title: wire.title,
            text: wire.text.map(|t| ItemText {
                plain: t.plain,
                html: t.html,
                markdown: t.markdown,
                source_format: SourceFormat::from_wire(t.source_format.as_deref()),
            }),
            url: wire.url,
            attachments,
            raw_payload: None,
        })
    }
}

/// Message of the error raised by [`NoDuplicateKeys`]; contains no input bytes.
const DUPLICATE_KEY_MSG: &str = "duplicate JSON key";

/// Rejects a payload in which any object, at any depth, has the same key twice
/// (`malformed_payload`, spec §5.4). Keys are compared after decoding the escapes
/// (`"a"` and `"\u0061"` are the same key), so two readers cannot disagree on which value
/// wins, including for fields neither of them knows.
///
/// Other syntax errors are left to the typed parse that follows.
fn reject_duplicate_keys(json: &[u8]) -> Result<()> {
    match serde_json::from_slice::<NoDuplicateKeys>(json) {
        Ok(_) => Ok(()),
        Err(e) if e.is_data() && e.to_string().contains(DUPLICATE_KEY_MSG) => {
            Err(CoreError::payload("duplicate key"))
        }
        Err(e) => Err(CoreError::payload(format!("json: {}", json_category(&e)))),
    }
}

/// Walks any JSON value without keeping it, failing on a repeated object key.
struct NoDuplicateKeys;

impl<'de> Deserialize<'de> for NoDuplicateKeys {
    fn deserialize<D: Deserializer<'de>>(d: D) -> std::result::Result<Self, D::Error> {
        d.deserialize_any(NoDuplicateKeysVisitor)
    }
}

struct NoDuplicateKeysVisitor;

impl<'de> Visitor<'de> for NoDuplicateKeysVisitor {
    type Value = NoDuplicateKeys;

    fn expecting(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("any JSON value")
    }

    fn visit_bool<E: de::Error>(self, _: bool) -> std::result::Result<Self::Value, E> {
        Ok(NoDuplicateKeys)
    }

    fn visit_i64<E: de::Error>(self, _: i64) -> std::result::Result<Self::Value, E> {
        Ok(NoDuplicateKeys)
    }

    fn visit_u64<E: de::Error>(self, _: u64) -> std::result::Result<Self::Value, E> {
        Ok(NoDuplicateKeys)
    }

    fn visit_f64<E: de::Error>(self, _: f64) -> std::result::Result<Self::Value, E> {
        Ok(NoDuplicateKeys)
    }

    fn visit_str<E: de::Error>(self, _: &str) -> std::result::Result<Self::Value, E> {
        Ok(NoDuplicateKeys)
    }

    fn visit_unit<E: de::Error>(self) -> std::result::Result<Self::Value, E> {
        Ok(NoDuplicateKeys)
    }

    fn visit_seq<A: SeqAccess<'de>>(
        self,
        mut seq: A,
    ) -> std::result::Result<Self::Value, A::Error> {
        while seq.next_element::<NoDuplicateKeys>()?.is_some() {}
        Ok(NoDuplicateKeys)
    }

    fn visit_map<A: MapAccess<'de>>(
        self,
        mut map: A,
    ) -> std::result::Result<Self::Value, A::Error> {
        let mut seen = HashSet::new();
        while let Some(key) = map.next_key::<String>()? {
            if !seen.insert(key) {
                return Err(de::Error::custom(DUPLICATE_KEY_MSG));
            }
            map.next_value::<NoDuplicateKeys>()?;
        }
        Ok(NoDuplicateKeys)
    }
}

/// serde_json messages may quote input bytes; only the category is kept so that no
/// plaintext ends up in error messages or logs.
pub(crate) fn json_category(e: &serde_json::Error) -> &'static str {
    match e.classify() {
        serde_json::error::Category::Io => "io",
        serde_json::error::Category::Syntax => "syntax",
        serde_json::error::Category::Data => "data",
        serde_json::error::Category::Eof => "eof",
    }
}

/// Test helper shared by the preservation tests of this crate.
#[cfg(test)]
pub(crate) mod testing {
    use super::*;

    /// Pretty-printed payload with unknown fields at several depths, odd spacing and a
    /// reserved `audience`, for the preservation tests of this crate.
    pub(crate) fn payload_with_unknown_fields(id: &str) -> Vec<u8> {
        let key = B64.encode([7u8; KEY_LEN]);
        let nonce = B64.encode([9u8; NONCE_PREFIX_LEN]);
        r#"{
  "future_flag" : true ,
  "id": "@ID@",
  "audience": {"to":[{"type":"device","id":"d2daf28457ef3d14c9c58d6f488e1844","role":"cc"}],"mode":2},
  "source_device":"0123456789abcdef0123456789abcdef",
  "created_at":1,
  "secret":true,
  "title":"Wi-Fi \"maison\"\n2e ligne \u00e9",
  "text":{"plain":"hunter2","lang":"fr","spans":[1,2.50,1e2,{"k":null}]},
  "attachments":[{"blob_id":"00000000-0000-4000-8000-0000000000aa","name":"a.txt","mime":"text/plain","size":3,
    "key":"@KEY@","nonce_prefix":"@NONCE@","duration_ms":1200,
    "thumbnail":{"mime":"image/png","data":"AAEC","w":16}}],
  "ext":{"x":1}
}"#
        .replace("@ID@", id)
        .replace("@KEY@", &key)
        .replace("@NONCE@", &nonce)
        .into_bytes()
    }
}

#[cfg(test)]
mod tests {
    use super::testing::payload_with_unknown_fields;
    use super::*;

    fn sample() -> Item {
        Item {
            id: "00000000-0000-4000-8000-000000000001".into(),
            source_device: "0123456789abcdef0123456789abcdef".into(),
            created_at_ms: 1,
            expires_at_ms: None,
            read_policy: ReadPolicy::UntilExpiry,
            secret: true,
            title: None,
            text: Some(ItemText {
                plain: "hunter2".into(),
                html: None,
                markdown: None,
                source_format: SourceFormat::Plain,
            }),
            url: None,
            attachments: vec![],
            raw_payload: None,
        }
    }

    #[test]
    fn json_roundtrip() {
        let it = sample();
        let json = it.to_json().unwrap();
        assert_eq!(Item::from_json(&json, &it.id).unwrap(), it);
    }

    #[test]
    fn debug_hides_secret() {
        let mut it = sample();
        it.title = Some("Code Wi-Fi".into());
        let dbg = format!("{it:?}");
        assert!(!dbg.contains("hunter2"));
        assert!(!dbg.contains("Wi-Fi"));
    }

    #[test]
    fn secret_title_is_masked_and_not_searchable() {
        let mut it = sample();
        it.title = Some("Code Wi-Fi".into());
        assert_eq!(it.visible_title(), None);
        assert_eq!(it.searchable_text(), None);
        it.secret = false;
        assert_eq!(it.visible_title(), Some("Code Wi-Fi"));
        assert_eq!(it.searchable_text().as_deref(), Some("Code Wi-Fi\nhunter2"));
    }

    #[test]
    fn duplicate_field_rejected() {
        let j = br#"{"id":"00000000-0000-4000-8000-000000000001","id":"00000000-0000-4000-8000-000000000001","source_device":"0123456789abcdef0123456789abcdef","created_at":1}"#;
        assert!(Item::from_json(j, "00000000-0000-4000-8000-000000000001").is_err());
    }

    const ID: &str = "00000000-0000-4000-8000-000000000001";

    /// Payload with a root-level duplicate-free minimum, then `extra` spliced in.
    fn with_extra(extra: &str) -> Vec<u8> {
        format!(
            r#"{{"id":"{ID}","source_device":"0123456789abcdef0123456789abcdef","created_at":1{extra}}}"#
        )
        .into_bytes()
    }

    fn duplicate_error(json: &[u8]) -> bool {
        matches!(
            Item::from_json(json, ID),
            Err(CoreError::MalformedPayload { reason }) if reason == "duplicate key"
        )
    }

    #[test]
    fn duplicate_unknown_keys_rejected_at_every_depth() {
        // Reserved field, unknown field, nested object, object in an array, key repeated
        // through an escape, and a duplicate hidden after a deeper structure.
        for extra in [
            r#","audience":1,"audience":2"#,
            r#","future":{"a":1},"future":null"#,
            r#","ext":{"a":1,"b":{"c":1,"c":2}}"#,
            r#","list":[{"k":1},{"k":1,"k":1}]"#,
            r#","audience":1,"\u0061udience":2"#,
            r#","a\u0062":1,"ab":2"#,
            r#","x":{"deep":[[{"y":0,"z":0,"y":1}]]},"after":1"#,
        ] {
            let json = with_extra(extra);
            assert!(duplicate_error(&json), "{extra}");
        }
        // Inside known sub-objects as well.
        let json = format!(
            r#"{{"id":"{ID}","source_device":"0123456789abcdef0123456789abcdef","created_at":1,"text":{{"plain":"a","extra":1,"extra":2}}}}"#
        );
        assert!(duplicate_error(json.as_bytes()));
        // A duplicate of a known field is still rejected.
        assert!(duplicate_error(&with_extra(
            r#","secret":true,"secret":false"#
        )));
    }

    #[test]
    fn number_outside_f64_range_is_malformed_even_in_unknown_field() {
        // Documented in spec §5.4; the strict pass cannot skip a number it cannot read.
        let json = with_extra(r#","x_big":1e999"#);
        assert_eq!(
            Item::from_json(&json, ID).unwrap_err().code(),
            "malformed_payload"
        );
        // Large but representable numbers are fine.
        let json = with_extra(r#","x_big":123456789012345678901234567890,"x_exp":1e300"#);
        assert!(Item::from_json(&json, ID).is_ok());
    }

    #[test]
    fn same_key_in_different_objects_is_fine() {
        let json = with_extra(r#","a":{"x":1},"b":{"x":2},"c":[{"x":1},{"x":2}]"#);
        let item = Item::from_json(&json, ID).unwrap();
        assert_eq!(item.raw_payload.unwrap().as_bytes(), &json[..]);
    }

    #[test]
    fn parsed_item_keeps_original_payload_bytes() {
        let json = payload_with_unknown_fields(ID);
        let item = Item::from_json(&json, ID).unwrap();
        assert_eq!(item.title.as_deref(), Some("Wi-Fi \"maison\"\n2e ligne é"));
        assert_eq!(item.attachments.len(), 1);
        assert_eq!(item.raw_payload.as_ref().unwrap().as_bytes(), &json[..]);
        // Writing it back is the identity, not a re-serialization of the known fields.
        assert_eq!(item.to_json().unwrap(), json);
        assert_ne!(item.to_known_json().unwrap(), json);
        assert!(!format!("{:?}", item.raw_payload).contains("hunter2"));
    }

    #[test]
    fn edited_item_cannot_reuse_stale_payload() {
        let json = payload_with_unknown_fields(ID);
        let mut item = Item::from_json(&json, ID).unwrap();
        item.url = Some("https://example.org".into());
        assert_eq!(item.to_json().unwrap_err().code(), "invalid_input");
        // Dropping the raw payload is the explicit way to rewrite it (unknown fields go).
        item.raw_payload = None;
        let rewritten = item.to_json().unwrap();
        let back = Item::from_json(&rewritten, ID).unwrap();
        assert_eq!(back, item);
        assert!(!String::from_utf8(rewritten)
            .unwrap()
            .contains("future_flag"));
    }
}
