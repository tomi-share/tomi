// Tomi: writes the logo SVG files (design/tomi/*.svg) from tomi-geometry.mjs, then the client assets
// (design/tomi/export/) rendered with @resvg/resvg-js (pinned in package-lock.json):
//   Windows  tomi.ico + tomi-<N>.png (app tile, N = 16 20 24 32 48 256),
//            tray-light.ico / tray-light-<N>.png (black, LIGHT taskbar) and tray-dark (white, DARK taskbar), N = 16 20 24 32
//   Android  android/ic_stat_tomi.xml (status bar, one white fill), android/ic_launcher_foreground.xml,
//            ic_launcher_monochrome.xml, ic_launcher_background.xml, ic_launcher.xml (adaptive icon)
//   Store    store/tomi-play-512.png (Google Play, full square, the store applies the mask)
// Which drawing at which size: 16, 20, 24 px pixel grids (logo-16/20/24.svg), 32 px and more master (guidelines 2.4).
// Self-checks, exit code 1 on failure: crisp pixel grids (alpha 0 or 255 only), only the requested colours,
// non-empty renders, .ico re-read, launcher inside the 66 dp safe zone, colours equal to tokens.json.
// Usage: cd design/build && npm ci && node tomi-export.mjs

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as G from './tomi-geometry.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const tomiDir = path.resolve(here, '..', 'tomi');
const outDir = path.join(tomiDir, 'export');

const fail = (msg) => {
  console.error(`FAILED: ${msg}`);
  process.exit(1);
};
let Resvg;
try {
  ({ Resvg } = await import('@resvg/resvg-js'));
} catch (e) {
  fail(`@resvg/resvg-js is not installed or has no binary for this platform (${e.message}). Run "npm ci" in design/build.`);
}

const tokens = JSON.parse(await readFile(path.join(tomiDir, 'tokens.json'), 'utf8'));
const tok = (n) => {
  if (!tokens[n]) fail(`unknown token ${n}`);
  return tokens[n].value;
};
if (tok('color.identity.night') !== G.NIGHT || tok('color.identity.sun') !== G.SUN) fail('tokens.json identity colours differ from tomi-geometry.mjs');

