for (const [name, content] of Object.entries(files)) await writeFile(path.join(tomiDir, name), content, 'utf8');

// ---------------- raster ----------------
const hexRgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
function render(svg, size, colors, crisp, label) {
  const r = new Resvg(svg, { fitTo: { mode: 'width', value: size }, background: 'rgba(0,0,0,0)', font: { loadSystemFonts: false } }).render();
  if (r.width !== size || r.height !== size) fail(`${label}: got ${r.width}x${r.height}`);
  const want = colors.map(hexRgb);
  const px = r.pixels;
  let opaque = 0;
  for (let i = 0; i < px.length; i += 4) {
    const a = px[i + 3];
    if (a === 0) continue;
    if (crisp && a !== 255) fail(`${label} is not crisp (alpha ${a}); check shape-rendering="crispEdges"`);
    if (a === 255) {
      opaque += 1;
      // anti-aliased renders may blend two colours of the same image at an edge; crisp ones may not
      const exact = want.some((w) => w.every((v, k) => Math.abs(px[i + k] - v) <= 1));
      if (crisp && !exact) fail(`${label}: pixel ${px[i]},${px[i + 1]},${px[i + 2]} is not one of ${colors.join(', ')}`);
    }
  }
  if (opaque < size) fail(`${label}: almost empty (${opaque} opaque pixels)`);
  return r.asPng();
}
const recolor = (svg, color) => svg.replace(/ color="#[0-9A-Fa-f]{6}"/, ` color="${color}"`);

// ICO = ICONDIR (6 bytes) + n x ICONDIRENTRY (16 bytes) + PNG payloads (PNG entries: Windows Vista and later).
function ico(entries) {
  const header = Buffer.alloc(6 + 16 * entries.length);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(entries.length, 4);
  let offset = header.length;
  entries.forEach(({ size, png }, i) => {
    const o = 6 + 16 * i;
    header.writeUInt8(size >= 256 ? 0 : size, o);
    header.writeUInt8(size >= 256 ? 0 : size, o + 1);
    header.writeUInt16LE(1, o + 4);
    header.writeUInt16LE(32, o + 6);
    header.writeUInt32LE(png.length, o + 8);
    header.writeUInt32LE(offset, o + 12);
    offset += png.length;
  });
  return Buffer.concat([header, ...entries.map((e) => e.png)]);
}
function checkIco(buf, sizes, name) {
  if (buf.readUInt16LE(2) !== 1 || buf.readUInt16LE(4) !== sizes.length) fail(`${name}: bad header`);
  sizes.forEach((s, i) => {
    const o = 6 + 16 * i;
    const w = buf.readUInt8(o) || 256;
    const png = buf.subarray(buf.readUInt32LE(o + 12), buf.readUInt32LE(o + 12) + buf.readUInt32LE(o + 8));
    if (w !== s || png.readUInt32BE(0) !== 0x89504e47 || png.readUInt32BE(16) !== s) fail(`${name}: entry ${i} is not a ${s} px PNG`);
  });
}

await mkdir(path.join(outDir, 'android'), { recursive: true });
await mkdir(path.join(outDir, 'store'), { recursive: true });
const written = [];
const out = async (rel, data) => {
  await writeFile(path.join(outDir, rel), data);
  written.push(rel);
};

// bare symbol: which drawing at which size
const bare = (size) => ([16, 20, 24].includes(size) ? { svg: files[`logo-${size}.svg`], crisp: true } : { svg: files['logo.svg'], crisp: false });
const appTile = (size) => (size <= 24 ? { svg: files[`logo-app-${size}.svg`], crisp: true } : { svg: files['logo-app.svg'], crisp: false });

const APP_SIZES = [16, 20, 24, 32, 48, 256];
const appEntries = [];
for (const s of APP_SIZES) {
  const { svg, crisp } = appTile(s);
  const png = render(svg, s, [G.NIGHT, G.SUN], crisp, `tomi-${s}`);
  await out(`tomi-${s}.png`, png);
  appEntries.push({ size: s, png });
}
const appIco = ico(appEntries);
checkIco(appIco, APP_SIZES, 'tomi.ico');
await out('tomi.ico', appIco);

const TRAY_SIZES = [16, 20, 24, 32];
for (const [variant, color] of [['light', '#000000'], ['dark', '#FFFFFF']]) {
  const entries = [];
  for (const s of TRAY_SIZES) {
    const { svg, crisp } = bare(s);
    const png = render(recolor(svg, color), s, [color], crisp, `tray-${variant}-${s}`);
    await out(`tray-${variant}-${s}.png`, png);
    entries.push({ size: s, png });
  }
  const buf = ico(entries);
  checkIco(buf, TRAY_SIZES, `tray-${variant}.ico`);
  await out(`tray-${variant}.ico`, buf);
}

// Google Play: 512 x 512, full square (Play applies its own mask), symbol at the tile's proportion.
const playSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" width="512" height="512"><rect width="256" height="256" fill="${G.NIGHT}"/><g transform="${G.TILE_SYM_TRANSFORM}">${G.symbolInner(G.SUN)}</g></svg>`;
await out('store/tomi-play-512.png', render(playSvg, 512, [G.NIGHT, G.SUN], false, 'play-512'));

// ---------------- Android VectorDrawable ----------------
const symPaths = [{ d: G.RING_D }, { d: G.BEAD_D }];
const vector = ({ comment, sizeDp, viewport, scale, tx, ty, fill }) => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by design/build/tomi-export.mjs, do not edit. ${comment} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${sizeDp}dp"
    android:height="${sizeDp}dp"
    android:viewportWidth="${viewport}"
    android:viewportHeight="${viewport}">
    <group
        android:scaleX="${scale}"
        android:scaleY="${scale}"
        android:translateX="${tx}"
        android:translateY="${ty}">
${symPaths.map((p) => `        <path\n            android:fillColor="${fill}"\n            android:pathData="${p.d}" />`).join('\n')}
    </group>
</vector>
`;
const r3 = (n) => Number(n.toFixed(3));
const bx = (G.SYM_BOX.x0 + G.SYM_BOX.x1) / 2;
const by = (G.SYM_BOX.y0 + G.SYM_BOX.y1) / 2;
const symW = G.SYM_BOX.x1 - G.SYM_BOX.x0;

// Status bar: 24 dp canvas, symbol 20 dp wide (2 dp padding), centred on its bounding box.
{
  const k = r3(((20 / 24) * 256) / symW);
  await out('android/ic_stat_tomi.xml', vector({
    comment: 'Notification small icon (res/drawable/). Android keeps only the alpha channel: one white fill, no colour.',
    sizeDp: 24, viewport: 256, scale: k, tx: r3(128 - bx * k), ty: r3(128 - by * k), fill: '#FFFFFFFF',
  }));
}
// Adaptive icon: 108 dp canvas, 72 dp visible, safe circle of 66 dp. Symbol at the tile's proportion of 72 dp.
const LS = r3((G.TILE_SCALE * 72) / 256);
const LT = [r3(54 - bx * LS), r3(54 - by * LS)];
const farthest = Math.max(
  Math.hypot(G.BEAD.x - G.M.br - bx, 0) * LS,
  (Math.hypot(G.M.cx - bx, G.M.cy - by) + G.M.R + G.M.w / 2) * LS,
);
if (farthest > 33) fail(`launcher foreground leaves the 66 dp safe zone (${farthest.toFixed(2)} dp)`);
const launcher = (comment, fill) => vector({ comment, sizeDp: 108, viewport: 108, scale: LS, tx: LT[0], ty: LT[1], fill });
await out('android/ic_launcher_foreground.xml', launcher('Adaptive icon foreground (res/drawable/): the symbol in sun yellow, inside the 66 dp safe zone.', `#FF${G.SUN.slice(1)}`));
await out('android/ic_launcher_monochrome.xml', launcher('Themed icon, Android 13+ (res/drawable/): same silhouette, the system tints it; only alpha matters.', '#FFFFFFFF'));
await out('android/ic_launcher_background.xml', `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by design/build/tomi-export.mjs, do not edit. Goes in res/values/. Value: color.identity.night. -->
<resources>
    <color name="ic_launcher_background">${G.NIGHT}</color>
</resources>
`);
await out('android/ic_launcher.xml', `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by design/build/tomi-export.mjs, do not edit. Goes in res/mipmap-anydpi-v26/ (also as ic_launcher_round.xml). -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
`);

